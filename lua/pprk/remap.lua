    vim.cmd("so")
end)

vim.keymap.set("n", "<leader>q", ":w !gcc % -o %:r && konsole --hold -e ./%:r<CR>")

-- Compile and run keymaps
-- F3: C++
-- F4: Rust
-- F5: C
-- F6: Java
-- F7: Python
-- F8: Go
-- F9: Node

